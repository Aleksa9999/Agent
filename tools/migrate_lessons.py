def md_list(items):
    return "\n".join(f"- {x}" for x in items)


def text_for(s):
    src = s["src"]
    store = S01 if src[0] == "01" else S02
    if src[0] == "01":
        return store[src[1]]
    # lesson 02: несколько подряд идущих разделов до end_at
    names = TITLES02
    i = names.index(src[1])
    j = names.index(s["end_at"]) if "end_at" in s and s["end_at"] in names else i + 1
    parts = []
    for n in names[i:j]:
        if n in store:
            parts.append(f"### {n}\n{store[n]}")
    return "\n\n".join(parts)


