def load(path, titles):
    lines = [l.strip() for l in path.read_text(encoding="utf-8").splitlines()]
    idx = {}
    for i, l in enumerate(lines):
        if l in titles and l not in idx:
            idx[l] = i
    order = sorted(idx.items(), key=lambda kv: kv[1])
    out = {}
    for n, (t, i) in enumerate(order):
        j = order[n + 1][1] if n + 1 < len(order) else len(lines)
        body = [l for l in lines[i + 1:j] if l]
        text = []
        for l in body:
            if l.startswith("## ") and text:
                text.append("")
            text.append(l)
        out[t] = "\n".join(text)
    return out


