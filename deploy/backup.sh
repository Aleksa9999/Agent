#!/usr/bin/env bash
# Database backup. Usage: deploy/backup.sh [--dry-run]
# Reads DATABASE_URL (plain postgresql://...) from the environment; never prints it.
# Env: BACKUP_DIR (default ./backups), BACKUP_KEEP (default 7), BACKUP_LABEL (default test)
set -euo pipefail

DRY_RUN=0
[[ "${1:-}" == "--dry-run" ]] && DRY_RUN=1

: "${DATABASE_URL:?DATABASE_URL is not set}"
BACKUP_DIR="${BACKUP_DIR:-./backups}"
BACKUP_KEEP="${BACKUP_KEEP:-7}"
LABEL="${BACKUP_LABEL:-test}"
STAMP="$(date -u +%Y%m%dT%H%M%SZ)"
TARGET="${BACKUP_DIR}/${LABEL}-${STAMP}.dump"

# pg_dump understands postgresql://; drop a SQLAlchemy driver suffix if present
PG_URL="${DATABASE_URL/postgresql+psycopg2:/postgresql:}"

if [[ $DRY_RUN -eq 1 ]]; then
  echo "dry-run: would write ${TARGET} and keep ${BACKUP_KEEP} newest ${LABEL} backups"
  exit 0
fi

mkdir -p "${BACKUP_DIR}"
chmod 700 "${BACKUP_DIR}"
pg_dump --format=custom --no-owner --file="${TARGET}" "${PG_URL}"
chmod 600 "${TARGET}"

# a backup that cannot be listed is not a backup
pg_restore --list "${TARGET}" >/dev/null

# rotation: keep only the newest N of this label
# shellcheck disable=SC2012  # file names are generated by this script
mapfile -t OLD < <(ls -1t "${BACKUP_DIR}/${LABEL}"-*.dump 2>/dev/null | tail -n +"$((BACKUP_KEEP + 1))")
for f in "${OLD[@]:-}"; do
  [[ -n "$f" ]] && rm -f -- "$f"
done

echo "backup ok: ${TARGET}"
